"""Write a static sample of what the demo shows, for the repository (no server needed).

.venv/bin/python demo/sample_output.py        # writes demo/SAMPLE_OUTPUT.md
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import server  # noqa: E402

MODEL = "v18-3b/D-d48-bpe1024-ctx512-r32_3000M_s0.pt"
PROMPTS = [
    ("Once upon a time", 1),
    ("The little dog was sad because", 3),
    ("One day, a girl named Mia found", 4),
]


def main() -> None:
    lines = [
        "# Sample demo output",
        "",
        f"Model `{MODEL}` (96,416 parameters, 0.9777 bits per character). Temperature 0.5, top-k 10, 60 word pieces, the seed shown.",
        "Generated by `demo/sample_output.py`; the live page shows the same numbers per piece. `^` marks a piece that repeats a three-piece run already in the text.",
        "",
    ]
    for prompt, seed in PROMPTS:
        out = server.generate(
            {
                "model": MODEL,
                "prompt": prompt,
                "max_tokens": 60,
                "temperature": 0.5,
                "top_k": 10,
                "seed": seed,
                "explain": True,
            }
        )
        text = prompt + "".join(
            s["text"] + ("^" if s["rep"] else "") for s in out["steps"]
        )
        lines += [f"## Prompt: {prompt}  (seed {seed})", "", "```", text, "```", ""]
        s = out["steps"][5]
        lines += [
            f"Piece 6, `{s['text']}` (the model gave it {s['p'] * 100:.1f}%). Top five at that point: "
            + ", ".join(f"`{c['text']}` {c['p'] * 100:.1f}%" for c in s["top"])
            + ".",
            "",
            "| layer | rule | gate | effect on this piece | the rule's strongest pushes |",
            "|---|---|---|---|---|",
        ]
        for r in s["rules"]:
            lines.append(
                f"| {r['layer']} | {r['rule']} | {r['gate']:.2f} | {r['contribution']:+.2f} | {' '.join(repr(x) for x in r['raises'])} |"
            )
        lines.append("")
    (HERE / "SAMPLE_OUTPUT.md").write_text("\n".join(lines))
    print("wrote", HERE / "SAMPLE_OUTPUT.md")


if __name__ == "__main__":
    main()
