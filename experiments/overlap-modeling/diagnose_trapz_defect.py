"""Reproduce the evidence for the trapezoid fitter's endpoint defect.

Stage 4's central claim is that `trapz_math_fast.fit_trapezoids_fast` places the
fitted support's left edge at ``data.min()``, while
`TrapezoidMembership.evaluate` returns exactly 0 there -- so every value tied with
a feature's minimum gets zero membership from the term fitted to describe it, and
under the ``min`` t-norm one such feature zeroes the whole rule.

That claim rests on three measurements, and this script regenerates all of them
rather than leaving them transcribed from a scratch probe:

1. `evaluate` really is 0 at ``x == a`` and ``x == d``;
2. how much of each feature sits exactly at its own minimum;
3. what fraction of rows end up covered by no rule, with and without padding, and
   that the bin count does not change it.

Usage: python experiments/overlap-modeling/diagnose_trapz_defect.py
Writes ``outputs/trapz_defect.md``.
"""

from __future__ import annotations

import contextlib
import io
import os
import sys
import warnings

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(REPO, "reproduce", "tables"))

warnings.filterwarnings("ignore")

from tribblefis.gauss_data import TrapezoidMembership  # noqa: E402

from overlap import OverlapTribbleRegressor  # noqa: E402
from run_experiment import DATASETS, PARTITION, prepare, split3  # noqa: E402

SEED = 0
N_BUCKETS = 5


def main():
    lines = ["<!-- generated by diagnose_trapz_defect.py -->", "",
             "# The trapezoid fitter's endpoint defect", "",
             f"One seed ({SEED}), {N_BUCKETS} buckets, `output_partition=\"{PARTITION}\"`. "
             "This file exists so stage 4's claim rests on regenerable numbers.", ""]

    # 1. the membership function's endpoint behaviour
    t = TrapezoidMembership.create(a=0.0, b=0.25, c=0.75, d=1.0)
    xs = np.array([-0.01, 0.0, 0.1, 0.5, 0.9, 1.0, 1.01])
    vals = t.evaluate(xs)
    lines += ["## 1. `TrapezoidMembership.evaluate` at its own endpoints", "",
              "`TrapezoidMembership(a=0, b=0.25, c=0.75, d=1)`:", "",
              "| x | " + " | ".join(f"{x:g}" for x in xs) + " |",
              "|---|" + "---|" * len(xs),
              "| membership | " + " | ".join(f"{v:.3f}" for v in vals) + " |", "",
              f"Membership at `x == a` is **{t.evaluate(np.array([0.0]))[0]:.3f}** and at "
              f"`x == d` is **{t.evaluate(np.array([1.0]))[0]:.3f}**. Correct for an open "
              "trapezoid; a defect once a fitter sets `a = data.min()`.", ""]

    # 2. mass at each feature's minimum, on the fold the model is fitted to
    X, y = DATASETS["concrete"]()
    inner, val, test = split3(X, y, SEED)
    (Xtr, ytr), _, (Xte, yte) = prepare(inner, [inner, val, test])
    lines += ["## 2. Mass sitting exactly at each feature's minimum", "",
              "Unit-scaled inner-train fold — the rows the memberships are fitted from.", "",
              "| feature | column min | fraction of rows at the min (train) | (test) |",
              "|---|---:|---:|---:|"]
    fracs = {}
    for name in Xtr.columns:
        col = Xtr[name].to_numpy(dtype=float)
        te = Xte[name].to_numpy(dtype=float)
        f_tr = float(np.mean(col == col.min()))
        fracs[name] = f_tr
        lines.append(f"| {name} | {col.min():.3f} | {f_tr:.3f} | "
                     f"{float(np.mean(te == col.min())):.3f} |")
    worst = sorted(fracs.items(), key=lambda kv: -kv[1])[:3]
    independent = 1.0 - np.prod([1.0 - f for _, f in worst])
    lines += ["",
              "The three worst columns are " + ", ".join(f"`{n}` ({f:.3f})" for n, f in worst)
              + f". If they were independent, {independent:.3f} of rows would be at the "
              "minimum of at least one of them — and under the `min` t-norm each of those "
              "rows is zeroed for **every** rule. The measured uncovered fraction below is "
              "the same order; the difference is that these columns are correlated.", ""]

    # 3. uncovered fraction against n_bins and pad
    bins = (1, 3, 12, 50)
    pads = (0.0, 0.05, 0.25)
    lines += ["## 3. Uncovered test rows, against bin count and padding", "",
              "`uncovered` is the fraction of test rows where no rule fires at all — those "
              "are answered with exactly 0, which is finite and so survives every NaN "
              "filter in the pipeline.", "",
              "| n_bins | " + " | ".join(f"pad={p:g}" for p in pads) + " |",
              "|---|" + "---|" * len(pads)]
    for b in bins:
        cells = []
        for p in pads:
            with contextlib.redirect_stdout(io.StringIO()):
                m = OverlapTribbleRegressor(
                    n_output_buckets=N_BUCKETS, output_partition=PARTITION,
                    tsk_order="2nd", l2_reg=1e-2, membership="trapezoid",
                    trapz_bins=b, trapz_pad=p, random_state=SEED).fit(Xtr, ytr)
                cells.append(f"{m.coverage(Xte)['uncovered']:.3f}")
        lines.append(f"| {b} | " + " | ".join(cells) + " |")
    lines += ["",
              "The `pad=0` column is constant in the bin count — the left edge tracks "
              "`data.min()` however many bins there are, which is why coarsening the "
              "histogram cannot fix this. Any nonzero pad removes it.", ""]

    out = os.path.join(HERE, "outputs", "trapz_defect.md")
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines))
    print(f"\nwrote {os.path.relpath(out, REPO)}")


if __name__ == "__main__":
    main()
