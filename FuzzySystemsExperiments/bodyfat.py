def main(csv, n_splits, seeds, report):
    t0 = time.perf_counter()
    df = pd.read_csv(csv)
    print(f"{csv}: {len(df)} rows, {len(df.columns)} columns")

    siri_rmse, siri_bad = check_leakage(df)
    print(
        f"\nSiri's equation ({SIRI[0]:.0f}/Density - {SIRI[1]:.0f}) reproduces "
        f"{TARGET} to RMSE {siri_rmse:.3f} pp"
    )
    print(f"  -> dropping `{LEAKY}`: it is the target in another coordinate")
    if len(siri_bad):
        print(f"  {len(siri_bad)} row(s) the equation does not reproduce (kept as-is):")
        print(siri_bad.to_string(float_format="%.2f"))

    bad_rows = implausible(df)
    for i in bad_rows:
        print(
            f"\n  row {i}: Height {df.loc[i, 'Height']:.1f} in at "
            f"{df.loc[i, 'Weight']:.1f} lb -- physically impossible, the known "
            f"height typo. Kept; also scored without it below."
        )

    features = [c for c in df.columns if c not in (TARGET, LEAKY)]
    X, y = df[features], df[TARGET].to_numpy(float)

    ranges = dynamic_ranges(df, features)
    print(
        "\nFeature dynamic ranges (decades). `MinMaxScaler`'s automatic log "
        "detection fires at 3.0, so it selects nothing here -- any log has to be "
        "named explicitly via `log_features`:"
    )
    print("  " + ", ".join(f"{r.feature} {r.decades:.2f}" for r in ranges.itertuples()))

    print(
        f"\n{n_splits}-fold CV over {len(seeds)} fold partitions (seeds "
        f"{', '.join(str(s) for s in seeds)}) on {len(features)} measurements, "
        f"{len(df)} rows:"
    )
    scores = score_all(X, y, features, n_splits, seeds)

    scores_dropped = None
    if bad_rows:
        kept = df.drop(index=bad_rows).reset_index(drop=True)
        print(f"\nSame, with row(s) {bad_rows} dropped ({len(kept)} rows):")
        scores_dropped = score_all(
            kept[features], kept[TARGET].to_numpy(float), features, n_splits, seeds
        )

    ctx = {
        "df": df,
        "n_rows": len(df),
        "features": features,
        "ranges": ranges,
        "siri_rmse": siri_rmse,
        "siri_bad": siri_bad,
        "implausible_rows": bad_rows,
        "n_splits": n_splits,
        "seeds": seeds,
        "scores": scores,
        "scores_dropped": scores_dropped,
        "wall_s": time.perf_counter() - t0,
    }
    write_report(report, ctx)
    print(f"\nwrote {report}")


