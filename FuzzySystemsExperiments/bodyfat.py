import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, r2_score
from sklearn.model_selection import KFold
from sklearn.preprocessing import StandardScaler

from tribblefis.gaussian_regressor import TribbleRegressor
from tribblefis.scaling import MinMaxScaler as FuzzyMinMaxScaler

REPORT = "FuzzySystemsExperiments/bodyfat_report.md"
DEFAULT_CSV = os.path.join("data", "bodyfat.csv")
TARGET = "BodyFat"
LEAKY = "Density"

# Siri's equation: the closed form the BodyFat column was generated by.
SIRI = (495.0, 450.0)

# Two configurations, and the gap between them is the point. Out of the box the
# estimator puts Gaussian antecedents on all 13 features and overfits 252 rows
# badly (RMSE ~7.5, fold spread +/-2.7). Capping the feature count and the
# Gaussians per feature, and leaning on the ridge, is what makes it competitive.
#
# `tuned` was chosen by a 288-point grid (top_n x n_gaussians x n_output_buckets
# x tsk_order x l2_reg) scored on seed 0's folds -- so it was selected with
# cross-validation visibility, and its seed-0 score is optimistic by
# construction. That is why every model here is re-scored over several
# *different* fold partitions: the selection seed is not the only one reported,
# and if the config were tuned to one partition's quirks the spread across seeds
# would show it.
CONFIGS = {
    "default": {},
    "tuned": {
        "top_n": 5,
        "n_gaussians": 2,
        "n_output_buckets": 4,
        "tsk_order": "1st",
        "l2_reg": 1.0,
    },
}

# The three-circumference subset, scored on its own because it is the natural
# question to ask of this dataset: abdomen, hip and chest are the measurements a
# clinician would actually take, and three features is a far better match for
# this estimator's capacity than thirteen. `TRIO_TUNED` is the best of a
# 144-point grid (n_gaussians x n_output_buckets x tsk_order x l2_reg) scored on
# *all* the partitions rather than one, so it carries no single-seed selection
# bias -- though picking the best of 144 on the same partitions it is reported on
# still flatters it a little, and the gap to OLS is larger than that flattery.
TRIO = ["Abdomen", "Hip", "Chest"]
TRIO_TUNED = {
    "n_gaussians": 1,
    "n_output_buckets": 4,
    "tsk_order": "1st",
    "l2_reg": 1e-2,
}

# The best fuzzy result on this dataset, and it comes from the *scaler*, not the
# estimator: `tribblefis.scaling.MinMaxScaler` bounding the three circumferences
# to [0, 1] after a log1p, with the config re-swept under that scaling.
#
# Three things about scaling on this dataset are worth stating, because each one
# is a trap:
#
#  1. **The default estimator is invariant to affine rescaling.** Raw features,
#     sklearn `StandardScaler`, `tribblefis` `MinMaxScaler` and `tribblefis`
#     `StandardScaler` all give byte-identical RMSE (7.021) for the default
#     config. Per-feature Gaussian membership fitting and least-squares
#     consequents are both unchanged by a per-feature affine map, so min-max vs
#     z-score cannot matter on its own. `tribblefis.scaling`'s warning that
#     z-scoring is actively harmful is documented for a pipeline with output
#     bucket means pinned to [0, 1] and a scaled target -- neither is in play
#     here, so it does not apply, and it is not contradicted either.
#
#  2. **Only a nonlinear transform moves the default model** -- which is what
#     makes the log the actual lever here (7.021 -> 6.358 on all 13).
#
#  3. **Automatic log detection never fires on this data.** It triggers at
#     `log_dynamic_range=3.0` decades, and the widest feature here spans 0.57
#     (`Age`); `Wrist` spans 0.13. So `MinMaxScaler()` and
#     `MinMaxScaler(log_dynamic_range=None)` are identical on bodyfat, and any
#     log has to be asked for explicitly with `log_features`. The script prints
#     the dynamic ranges so this is checkable rather than asserted.
#
# The log helps the fuzzy model (5.05 -> 4.82 on the trio) and *hurts* OLS
# (4.71 -> 5.36): the relationship really is closer to linear in raw units, and
# the log buys the fuzzy system a rule partition that fits better than it buys
# the linear model. Selected as the best of 64 configs scored on all the
# partitions, so it is mildly optimistic -- but the sixth-best log config
# (4.882) still beats the best no-log config (5.052), so the transform is doing
# the work rather than the search.
TRIO_LOG_TUNED = {
    "n_gaussians": 1,
    "n_output_buckets": 3,
    "tsk_order": "2nd",
    "l2_reg": 1e-2,
}


def fuzzy_log_scaler(cols):
    """`tribblefis`' own FIS scaler: log1p then bound to [0, 1], logging the
    named columns explicitly because automatic detection cannot fire here."""
    return lambda: FuzzyMinMaxScaler(log_features=list(cols))


def dynamic_ranges(df, cols):
    """Each feature's dynamic range in decades -- log10(max/min) over non-zero
    absolute values, the quantity `log_dynamic_range` thresholds."""
    rows = []
    for c in cols:
        v = np.abs(df[c].to_numpy(float))
        v = v[v > 0]
        rows.append({"feature": c, "decades": float(np.log10(v.max() / v.min()))})
    return pd.DataFrame(rows).sort_values("decades", ascending=False)


def rmse(y_true, y_pred):
    return float(np.sqrt(np.mean((np.asarray(y_true) - np.asarray(y_pred)) ** 2)))


def siri(density):
    """Body fat % from body density -- the equation this dataset's target came
    from."""
    a, b = SIRI
    return a / np.asarray(density, float) - b


def check_leakage(df):
    """Reconstruct the target from `Density` and report the residual, so the
    decision to drop that column rests on a number rather than on a claim.
    Returns (residual RMSE, frame of rows the equation does not reproduce)."""
    implied = siri(df[LEAKY])
    resid = df[TARGET].to_numpy(float) - implied
    bad = df.loc[np.abs(resid) > 1.0, [LEAKY, TARGET]].assign(
        siri_implied=implied[np.abs(resid) > 1.0], residual=resid[np.abs(resid) > 1.0]
    )
    return rmse(df[TARGET], implied), bad


def implausible(df):
    """Rows that cannot be physically right. Only one rule is needed here -- an
    adult height under 4 feet -- and it catches the dataset's known height typo.
    Reported, never silently repaired."""
    return df.index[df["Height"] < 48].tolist()


def cv_scores(model_factory, X, y, n_splits, seed, scale=True, scaler=None):
    """k-fold CV. The scaler is fit inside each fold, on the training part only.
    `scaler` is a zero-argument factory; it defaults to sklearn's
    `StandardScaler` when `scale` is true, and `scale=False` skips scaling
    entirely. Returns per-fold (rmse, mae, r2) and the out-of-fold predictions."""
    kf = KFold(n_splits=n_splits, shuffle=True, random_state=seed)
    oof = np.zeros(len(y), float)
    folds = []
    make_scaler = scaler or (StandardScaler if scale else None)
    for tr, te in kf.split(X):
        X_tr, X_te = X.iloc[tr], X.iloc[te]
        if make_scaler is not None:
            fitted = make_scaler().fit(X_tr)
            X_tr = pd.DataFrame(fitted.transform(X_tr), columns=X.columns)
            X_te = pd.DataFrame(fitted.transform(X_te), columns=X.columns)
        pred = model_factory().fit(X_tr, y[tr]).predict(X_te)
        pred = np.asarray(pred, float).ravel()
        oof[te] = pred
        folds.append(
            (rmse(y[te], pred), mean_absolute_error(y[te], pred), r2_score(y[te], pred))
        )
    return np.array(folds), oof


def multi_seed_scores(model_factory, X, y, n_splits, seeds, scale=True, scaler=None):
    """The same CV repeated over several fold partitions. Returns the per-seed
    (rmse, mae, r2) means, the worst single fold's RMSE, and how many
    under-filled-bucket warnings the estimator raised -- the library's own signal
    that some rules were fitted on almost no data, which an aggregate RMSE
    hides."""
    per_seed, worst_fold, n_warnings = [], 0.0, 0
    for seed in seeds:
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            with contextlib.redirect_stdout(io.StringIO()):
                folds, _ = cv_scores(
                    model_factory, X, y, n_splits, seed, scale=scale, scaler=scaler
                )
        n_warnings += sum("under-filled" in str(w.message) for w in caught)
        worst_fold = max(worst_fold, folds[:, 0].max())
        per_seed.append(folds.mean(axis=0))
    return np.array(per_seed), worst_fold, n_warnings


class MeanRegressor:
    """The floor: predict the training mean for everyone."""

    def fit(self, X, y):
        self.mean_ = float(np.mean(y))
        return self

    def predict(self, X):
        return np.full(len(X), self.mean_)


def score_all(X, y, features, n_splits, seeds, quiet=False):
    """Every model in the comparison, scored identically over the same fold
    partitions."""
    rows = []

    def add(name, factory, cols=None, scale=True, scaler=None, note=""):
        per_seed, worst, n_warn = multi_seed_scores(
            factory,
            X[cols] if cols else X,
            y,
            n_splits,
            seeds,
            scale=scale,
            scaler=scaler,
        )
        rows.append(
            {
                "model": name,
                "scaling": note or ("z-score" if scale else "none"),
                "RMSE": per_seed[:, 0].mean(),
                "RMSE sd": per_seed[:, 0].std(),
                "MAE": per_seed[:, 1].mean(),
                "R2": per_seed[:, 2].mean(),
                "worst fold": worst,
                "starved-rule warnings": n_warn,
            }
        )
        if not quiet:
            print(
                f"  {name:38s} {rows[-1]['scaling']:14s} "
                f"RMSE {rows[-1]['RMSE']:5.2f} "
                f"± {rows[-1]['RMSE sd']:4.2f}  MAE {rows[-1]['MAE']:5.2f}  "
                f"R2 {rows[-1]['R2']:6.3f}  worst fold {worst:5.2f}"
                + (f"  [{n_warn} starved-rule warnings]" if n_warn else "")
            )
        return rows[-1]

    trio = "+".join(TRIO)
    add("mean predictor", MeanRegressor, scale=False)
    add("OLS, Abdomen only", LinearRegression, cols=["Abdomen"])
    add(f"OLS, {trio}", LinearRegression, cols=TRIO)
    add(f"OLS, all {len(features)} features", LinearRegression)
    for label, cfg in CONFIGS.items():
        add(
            f"TribbleRegressor ({label}), all {len(features)}",
            lambda c=cfg: TribbleRegressor(random_state=0, **c),
        )
    add(
        f"TribbleRegressor (default), {trio}",
        lambda: TribbleRegressor(random_state=0),
        cols=TRIO,
    )
    add(
        f"TribbleRegressor (tuned), {trio}",
        lambda: TribbleRegressor(random_state=0, **TRIO_TUNED),
        cols=TRIO,
    )
    add(
        f"TribbleRegressor (log-tuned), {trio}",
        lambda: TribbleRegressor(random_state=0, **TRIO_LOG_TUNED),
        cols=TRIO,
        scaler=fuzzy_log_scaler(TRIO),
        note="log1p + [0,1]",
    )
    return pd.DataFrame(rows)


def md_table(frame):
    cols = list(frame.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, row in frame.iterrows():
        lines.append(
            "| "
            + " | ".join(
                f"{row[c]:.3f}" if isinstance(row[c], float) else str(row[c])
                for c in cols
            )
            + " |"
        )
    return "\n".join(lines)


