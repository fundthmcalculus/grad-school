"""Body fat % from body measurements, with `TribbleRegressor`.

The Penrose/Johnson body-fat dataset (252 men, 15 columns) with `BodyFat` as the
target.

**`Density` is not a feature -- it is the answer.** The dataset's `BodyFat`
column was not measured independently; it was *computed* from `Density` by
Siri's equation, %BF = 495/D - 450. Handing the model `Density` is therefore
handing it the target through a two-parameter closed form, and the resulting
near-perfect fit measures nothing. This script does not assert that -- it
reconstructs `BodyFat` from `Density` with Siri's equation and reports the
residual, then drops the column. Everything below predicts from the 13
anthropometric measurements (age, weight, height, and ten circumferences),
which is the problem worth solving: those are what a tape measure gives you,
where a hydrostatic-weighing tank is what `Density` needs.

Scored by 5-fold CV rather than one split -- 252 rows makes a single 20 % holdout
about 50 rows, too few for a stable RMSE -- repeated over five different fold
partitions, against three baselines: predicting the training mean, ordinary least
squares on the same 13 features, and OLS on `Abdomen` alone (one tape
measurement, the known dominant predictor). A fuzzy system that cannot beat one
circumference is not doing anything.

**The result is a draw at three features and a loss at thirteen.** OLS on all 13
measurements wins outright (RMSE 4.49). The fuzzy system's best configuration --
`tribblefis.scaling.MinMaxScaler` with an explicit log1p on the three
circumferences, config re-swept under that scaling -- reaches 4.82, level with
OLS on those same three features (4.71) and far better than the 7.02 it gets out
of the box. Body fat is close to linear in these circumferences, so the linear
model is hard to beat on its own ground.

**Scaling is the biggest lever here, and it is subtle.** The default estimator is
*invariant* to affine rescaling (raw, sklearn z-score, `tribblefis` min-max and
`tribblefis` z-score all give byte-identical RMSE), so only a nonlinear transform
moves it -- but affine scaling still matters indirectly, because `top_n` and
`l2_reg` are not scale-free and a config swept under one scaling does not
transfer to another. Automatic log detection never fires on this data (widest
feature spans 0.57 decades against a 3.0-decade threshold), so the log has to be
requested with `log_features`; the script prints the dynamic ranges so that is
checkable. The log helps the fuzzy model (5.05 -> 4.82) and hurts OLS
(4.71 -> 5.36).

The `Abdomen + Hip + Chest` subset is scored separately -- three circumferences
are a far better match for this estimator's capacity than thirteen features, and
it is the subset a clinician would actually measure. It is where every good fuzzy
result here comes from, and it also buys *stability*: the z-scored trio config
has a spread of 0.04 across fold partitions against 0.22 for the thirteen-feature
one. The interesting shape is that the fuzzy system scores about the same on
three features as on thirteen while OLS keeps improving as features are added --
the extra measurements carry linear information this configuration does not
convert into accuracy.

The Siri residual check also surfaces the dataset's known transcription errors as
a side effect, and physically impossible rows are reported and scored both ways
(kept and dropped), since a demo that silently repairs its data is not
reproducible.

Needs: numpy, pandas, scikit-learn, tribble-fis.  Run from the repo root:

    uv run --project tribble-fis python FuzzySystemsExperiments/bodyfat.py

Writes `FuzzySystemsExperiments/bodyfat_report.md`.
"""

